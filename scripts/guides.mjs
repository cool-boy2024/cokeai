export function renderGuideHtml(guide) {
  const escape = (value) =>
    String(value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  const list = (tag, items) =>
    `<${tag}>${items.map((item) => `<li>${escape(item)}</li>`).join("")}</${tag}>`;
  return [
    `<p>${escape(guide.intro)}</p>`,
    "<h3>操作步骤</h3>",
    list("ol", guide.steps),
    "<h3>注意事项</h3>",
    list("ul", guide.notes),
    "<p>遇到商品页没有覆盖的问题，请在订单页提交售后，我们会按订单核实处理。</p>",
  ].join("\n");
}
